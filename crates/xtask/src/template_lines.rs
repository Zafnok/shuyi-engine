//! `cargo xtask template-lines`: the lines a game's author owns, in each
//! game the engine's template makes and each example (ticket 2512), and
//! the cap on the minimal template's code (`tools/line-budget.ron`).
//!
//! Every file gets a kind: code, tests, data, setup or left out
//! ([`kind_of`]). A line counts when it isn't blank and isn't only a
//! comment ([`count`]); Rust and RON are read with
//! [`shuyi_cli::rust_lines`], the scanner `check-keys` uses, so a `//`, a
//! `/*` or a brace inside a string changes nothing.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use shuyi_cli::contract::new::{NewInput, plan};
use shuyi_cli::rust_lines::{exempt_lines, lex};
use shuyi_cli::template::{BUILT_IN_ORIGIN, Template};

/// Where the cap is, from the repository's root.
pub const BUDGET: &str = "tools/line-budget.ron";

/// What `--check` says a part every new game needs does instead.
const IN_THE_ENGINE: &str = "a part every new game needs goes in the engine, where every game \
                             gets it (ADR-0036)";

/// The command's options.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Options {
    /// The folders (or the template's short names) given; none for all.
    pub folders: Vec<String>,
    /// Print JSON instead of the table.
    pub json: bool,
    /// Hold the capped template to [`BUDGET`].
    pub check: bool,
    /// Append the table's Markdown to this file.
    pub summary: Option<PathBuf>,
}

impl Options {
    /// Reads `args` (after the command's name); `None` when they're wrong.
    pub fn parse(args: &[String]) -> Option<Self> {
        let mut options = Self::default();
        let mut rest = args.iter();
        while let Some(arg) = rest.next() {
            match arg.as_str() {
                "--json" => options.json = true,
                "--check" => options.check = true,
                "--summary" => options.summary = Some(PathBuf::from(rest.next()?)),
                flag if flag.starts_with("--") => return None,
                folder => options.folders.push(folder.to_owned()),
            }
        }
        Some(options)
    }
}

/// What a file is to the game's author.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Kind {
    /// Rust outside `tests/`, without its `#[cfg(test)]` items.
    Code,
    /// Rust under `tests/` or named `tests.rs`.
    Tests,
    /// Text under a `files/` folder.
    Data,
    /// The manifests and the tools' settings.
    Setup,
    /// Not counted: Markdown, pictures, licenses, generated files, builds.
    LeftOut,
}

impl Kind {
    /// Its name in `--json`.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Code => "code",
            Self::Tests => "tests",
            Self::Data => "data",
            Self::Setup => "setup",
            Self::LeftOut => "left-out",
        }
    }
}

/// The setup files, by name, wherever they are.
const SETUP_NAMES: [&str; 5] = [
    "Cargo.toml",
    "shuyi.ron",
    "rust-toolchain.toml",
    "rustfmt.toml",
    "clippy.toml",
];

/// The folders whose files are never the author's: the builds, and the
/// engine's skill pack (`.claude/skills/`, with its worked examples, and
/// Codex's loaders in `.agents/`), which its updater replaces.
const LEFT_OUT_DIRS: [&str; 5] = [".git", "target", "dist", ".claude", ".agents"];

/// The kind of the file at `path` (`/`-separated, from the game's folder),
/// whose bytes are `bytes`.
pub fn kind_of(path: &str, bytes: &[u8]) -> Kind {
    let parts: Vec<&str> = path.split('/').collect();
    let (name, dirs) = parts.split_last().unwrap_or((&"", &[]));
    let upper = name.to_ascii_uppercase();
    let Ok(text) = std::str::from_utf8(bytes) else {
        return Kind::LeftOut;
    };
    let first = text.lines().next().unwrap_or("");
    let left_out = dirs.iter().any(|d| LEFT_OUT_DIRS.contains(d))
        || *name == "Cargo.lock"
        || has_ext(name, "md")
        || ["LICENSE", "LICENCE", "NOTICE", "COPYING"]
            .iter()
            .any(|l| upper.contains(l))
        || first.contains("Generated by") && first.contains("Do not edit");
    if left_out {
        Kind::LeftOut
    } else if has_ext(name, "rs") {
        if dirs.contains(&"tests") || *name == "tests.rs" {
            Kind::Tests
        } else {
            Kind::Code
        }
    } else if dirs.iter().any(|d| is_files_dir(d)) {
        Kind::Data
    } else if SETUP_NAMES.contains(name)
        || dirs == [".cargo"] && *name == "config.toml"
        || dirs.first() == Some(&".github") && (has_ext(name, "yml") || has_ext(name, "yaml"))
    {
        Kind::Setup
    } else {
        Kind::LeftOut
    }
}

/// A game's data folder: `files/`, or a target's own (`files@playdate/`).
fn is_files_dir(dir: &str) -> bool {
    dir == "files" || dir.starts_with("files@")
}

fn has_ext(name: &str, ext: &str) -> bool {
    Path::new(name)
        .extension()
        .is_some_and(|e| e.eq_ignore_ascii_case(ext))
}

/// The lines of `text` that count, from a file named `name`: for Rust,
/// those outside `#[cfg(test)]` items, then those inside them.
pub fn count(name: &str, text: &str) -> (usize, usize) {
    let ext = Path::new(name)
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("");
    match ext {
        "rs" | "ron" => {
            let lines = lex(text);
            let exempt = if ext == "rs" {
                exempt_lines(&lines, None)
            } else {
                vec![false; lines.len()]
            };
            let raw: Vec<&str> = text.split('\n').collect();
            let mut counts = (0, 0);
            for (i, line) in lines.iter().enumerate() {
                let in_string = line.in_string && raw.get(i).is_some_and(|r| !r.trim().is_empty());
                if !in_string && line.code.trim().is_empty() {
                    continue;
                }
                if exempt.get(i).copied().unwrap_or(false) {
                    counts.1 += 1;
                } else {
                    counts.0 += 1;
                }
            }
            counts
        }
        "map" => (marked(text, "//"), 0),
        "dlg" | "toml" | "yml" | "yaml" => (marked(text, "#"), 0),
        _ => (text.lines().filter(|l| !l.trim().is_empty()).count(), 0),
    }
}

/// The lines of `text` that aren't blank and don't start with `marker`.
fn marked(text: &str, marker: &str) -> usize {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with(marker))
        .count()
}

/// One file of a game, as counted.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    /// Its path from the game's folder, `/`-separated.
    pub path: String,
    pub kind: Kind,
    /// The lines of its kind that count (0 when left out).
    pub lines: usize,
    /// A code file's lines in `#[cfg(test)]` items, counted as tests.
    pub test_lines: usize,
}

/// One game's counts.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Counts {
    /// The folder, or the template's short name.
    pub folder: String,
    pub code: usize,
    pub tests: usize,
    pub data: usize,
    pub setup: usize,
    /// Every file, in path order.
    pub files: Vec<File>,
}

/// Counts the files of a game called `folder`, each by its path
/// (`/`-separated) and bytes.
pub fn count_files(folder: &str, files: &BTreeMap<String, Vec<u8>>) -> Counts {
    let mut counts = Counts {
        folder: folder.to_owned(),
        ..Counts::default()
    };
    for (path, bytes) in files {
        let kind = kind_of(path, bytes);
        let (lines, test_lines) = match (kind, std::str::from_utf8(bytes)) {
            (Kind::LeftOut, _) | (_, Err(_)) => (0, 0),
            (_, Ok(text)) => count(path, text),
        };
        match kind {
            Kind::Code => {
                counts.code += lines;
                counts.tests += test_lines;
            }
            Kind::Tests => counts.tests += lines + test_lines,
            Kind::Data => counts.data += lines,
            Kind::Setup => counts.setup += lines,
            Kind::LeftOut => {}
        }
        let (lines, test_lines) = if kind == Kind::Tests {
            (lines + test_lines, 0)
        } else {
            (lines, test_lines)
        };
        counts.files.push(File {
            path: path.clone(),
            kind,
            lines,
            test_lines,
        });
    }
    counts
}

/// The files under `dir`, by their `/`-separated paths from it, never
/// inside `.git/`, `target/` or `dist/`.
pub fn read_dir(dir: &Path) -> Result<BTreeMap<String, Vec<u8>>, String> {
    let mut files = BTreeMap::new();
    let mut todo = vec![dir.to_path_buf()];
    while let Some(at) = todo.pop() {
        let entries = std::fs::read_dir(&at).map_err(|e| format!("{}: {e}", at.display()))?;
        for entry in entries {
            let path = entry.map_err(|e| format!("{}: {e}", at.display()))?.path();
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if path.is_dir() {
                if !LEFT_OUT_DIRS.contains(&name) {
                    todo.push(path);
                }
                continue;
            }
            let bytes = std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            files.insert(shown(path.strip_prefix(dir).unwrap_or(&path)), bytes);
        }
    }
    Ok(files)
}

/// `path` with `/` between its parts, on Windows too.
fn shown(path: &Path) -> String {
    path.components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

/// The engine's template, from this checkout.
pub fn template(root: &Path) -> Result<Template, String> {
    let dir = root.join(BUILT_IN_ORIGIN);
    Template::load(&dir).map_err(|e| format!("{}: {e}", dir.display()))
}

/// The files the template makes for its short name `name`, as `shuyi new`
/// fills them; none is written.
pub fn composed(
    root: &Path,
    template: &Template,
    name: &str,
) -> Result<BTreeMap<String, Vec<u8>>, String> {
    let input = NewInput::new(name).template(name);
    let (plan, _) =
        plan(root, template, &input, name, name).map_err(|(_, e)| format!("{name}: {e}"))?;
    Ok(plan
        .files
        .into_iter()
        .map(|(path, bytes)| (shown(&path), bytes))
        .collect())
}

/// Counts what `options` names: each of the template's short names and
/// each folder under `examples/`, or the folders (or short names) given.
pub fn run(root: &Path, options: &Options) -> Result<Vec<Counts>, String> {
    let template = template(root)?;
    let names: Vec<String> = if options.folders.is_empty() {
        let mut names: Vec<String> = template.short_names.keys().cloned().collect();
        let mut examples: Vec<String> = std::fs::read_dir(root.join("examples"))
            .map_err(|e| format!("examples: {e}"))?
            .filter_map(Result::ok)
            .filter(|e| e.path().is_dir())
            .map(|e| format!("examples/{}", e.file_name().to_string_lossy()))
            .collect();
        examples.sort();
        names.extend(examples);
        names
    } else {
        options.folders.clone()
    };
    names
        .iter()
        .map(|name| {
            let files = if template.short_names.contains_key(name) {
                composed(root, &template, name)?
            } else {
                read_dir(&root.join(name))?
            };
            Ok(count_files(&name.replace('\\', "/"), &files))
        })
        .collect()
}

/// The table: folder, code, tests, data, setup.
pub fn table(all: &[Counts]) -> String {
    let width = all
        .iter()
        .map(|c| c.folder.len())
        .chain(std::iter::once("Folder".len()))
        .max()
        .unwrap_or(0);
    let mut out = format!(
        "{:<width$}  {:>5}  {:>5}  {:>5}  {:>5}\n",
        "Folder", "Code", "Tests", "Data", "Setup"
    );
    for c in all {
        let _ = writeln!(
            out,
            "{:<width$}  {:>5}  {:>5}  {:>5}  {:>5}",
            c.folder, c.code, c.tests, c.data, c.setup
        );
    }
    out
}

/// The table in Markdown, for a run's summary.
pub fn markdown(all: &[Counts]) -> String {
    let mut out = String::from(
        "### Lines a game's author owns\n\n\
         | Folder | Code | Tests | Data | Setup |\n\
         | ------ | ---- | ----- | ---- | ----- |\n",
    );
    for c in all {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            c.folder, c.code, c.tests, c.data, c.setup
        );
    }
    out
}

/// The counts as JSON, with every file's path, kind and lines.
pub fn json(all: &[Counts]) -> serde_json::Value {
    let folders: Vec<serde_json::Value> = all
        .iter()
        .map(|c| {
            let files: Vec<serde_json::Value> = c
                .files
                .iter()
                .map(|f| {
                    let mut file = serde_json::json!({
                        "path": f.path,
                        "kind": f.kind.name(),
                        "lines": f.lines,
                    });
                    if f.test_lines > 0 {
                        file["test_lines"] = f.test_lines.into();
                    }
                    file
                })
                .collect();
            serde_json::json!({
                "folder": c.folder,
                "code": c.code,
                "tests": c.tests,
                "data": c.data,
                "setup": c.setup,
                "files": files,
            })
        })
        .collect();
    serde_json::Value::Array(folders)
}

/// The cap, `tools/line-budget.ron`.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Budget {
    /// The template's short name it caps.
    pub template: String,
    /// The most code lines its game may have.
    pub code: usize,
}

/// Reads the cap's text.
pub fn parse_budget(text: &str) -> Result<Budget, String> {
    ron::from_str(text).map_err(|e| e.to_string())
}

/// `count` rounded up to a multiple of 10.
pub const fn rounded(count: usize) -> usize {
    count.div_ceil(10) * 10
}

/// What holding `counts` to `budget` finds: an error over the cap, or 10
/// or more under it.
pub fn check(counts: &Counts, budget: &Budget) -> Vec<String> {
    let (count, cap) = (counts.code, budget.code);
    if count > cap {
        let mut code: Vec<&File> = counts
            .files
            .iter()
            .filter(|f| f.kind == Kind::Code)
            .collect();
        code.sort_by(|a, b| b.lines.cmp(&a.lines).then_with(|| a.path.cmp(&b.path)));
        let biggest: Vec<String> = code
            .iter()
            .take(5)
            .map(|f| format!("{} ({})", f.path, f.lines))
            .collect();
        vec![format!(
            "{}: {count} code lines, over the cap of {cap} in {BUDGET}; its biggest code files: \
             {}. Don't raise the cap: {IN_THE_ENGINE}",
            budget.template,
            biggest.join(", ")
        )]
    } else if cap - count >= 10 {
        vec![format!(
            "{}: {count} code lines, {} under the cap of {cap}: lower `code` to {} in {BUDGET}",
            budget.template,
            cap - count,
            rounded(count)
        )]
    } else {
        Vec::new()
    }
}

