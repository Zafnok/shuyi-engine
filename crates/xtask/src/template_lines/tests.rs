#[test]
fn a_folder_on_disk_is_read_with_slashes_and_without_its_builds() {
    let dir = std::env::temp_dir().join(format!("xtask-template-lines-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("src/ui")).unwrap();
    std::fs::create_dir_all(dir.join("target/debug")).unwrap();
    std::fs::write(dir.join("src/ui/title.rs"), "fn f() {}\n").unwrap();
    std::fs::write(dir.join("target/debug/x.rs"), "fn f() {}\n").unwrap();
    let files = read_dir(&dir);
    let _ = std::fs::remove_dir_all(&dir);
    let paths: Vec<String> = files.unwrap().into_keys().collect();
    assert_eq!(paths, vec!["src/ui/title.rs".to_owned()]);
}

#[test]
fn options_read_folders_and_flags() {
    let args: Vec<String> = ["blank", "--json", "--check", "--summary", "s.md"]
        .iter()
        .map(|s| (*s).to_owned())
        .collect();
    let options = Options::parse(&args).unwrap();
    assert_eq!(options.folders, vec!["blank".to_owned()]);
    assert!(options.json && options.check);
    assert_eq!(options.summary, Some(PathBuf::from("s.md")));
    assert_eq!(Options::parse(&["--summary".to_owned()]), None);
    assert_eq!(Options::parse(&["--nope".to_owned()]), None);
}

#[test]
fn the_templates_and_examples_here_are_counted() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let all = run(&root, &Options::default()).unwrap();
    let folders: Vec<&str> = all.iter().map(|c| c.folder.as_str()).collect();
    assert!(folders.starts_with(&["blank", "grid"]), "{folders:?}");
    assert!(folders.contains(&"examples/hello-grid"), "{folders:?}");
    let blank = &all[0];
    assert!(blank.code > 0 && blank.setup > 0, "{blank:?}");
    let budget = std::fs::read_to_string(root.join(BUDGET)).unwrap();
    assert_eq!(
        check(blank, &parse_budget(&budget).unwrap()),
        Vec::<String>::new()
    );
}
