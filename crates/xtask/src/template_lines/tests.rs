#[test]
fn the_budget_reads_its_one_record() {
    assert_eq!(
        parse_budget("// a comment\n(template: \"blank\", code: 210)\n"),
        Ok(cap(210))
    );
    assert!(parse_budget("(template: \"blank\", code: 210, tests: 1)").is_err());
}

