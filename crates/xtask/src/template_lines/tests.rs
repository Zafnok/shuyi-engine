use super::*;

/// Code and test lines of Rust source.
fn rs(source: &str) -> (usize, usize) {
    count("src/lib.rs", source)
}

#[test]
fn blank_lines_and_line_comments_do_not_count() {
    let source = "//! The crate.\n\n/// A function.\nfn f() {}\n    // inside\n\t\n";
    assert_eq!(rs(source), (1, 0));
}

#[test]
fn a_block_comment_over_several_lines_does_not_count() {
    assert_eq!(rs("/* one\n two\n three */\nfn f() {}\n"), (1, 0));
}

#[test]
fn a_nested_block_comment_closes_at_its_last_end() {
    assert_eq!(rs("/* a /* b */\n still a comment */\nfn f() {}\n"), (1, 0));
}

#[test]
fn a_code_line_ending_in_a_comment_counts() {
    assert_eq!(rs("let a = 1; // one\nlet b = 2; /* two */\n"), (2, 0));
}

#[test]
fn comment_markers_inside_a_string_count() {
    let source = "let a = \"// not a comment\";\nlet b = \"/* nor this\";\nlet c = 3;\n";
    assert_eq!(rs(source), (3, 0));
}

#[test]
fn the_lines_inside_a_string_that_spans_lines_count() {
    let source = "const HELP: &str = \"\n  one\n\n  two\n\";\n";
    // The blank line inside it is still blank.
    assert_eq!(rs(source), (4, 0));
    let raw = "const R: &str = r#\"\n// in the string\n}\n\"#;\n";
    assert_eq!(rs(raw), (4, 0));
}

#[test]
fn a_cfg_test_module_is_tests_even_with_brackets_in_strings_and_chars() {
    let source = "fn real() {}\n\
                  #[cfg(test)]\n\
                  mod tests {\n\
                  \x20   fn a<'a>(x: &'a str) -> char { let _ = \"}\"; '{' }\n\
                  \x20   fn b() { if true { let _ = r#\"}}\"#; } }\n\
                  }\n\
                  fn after() {}\n";
    assert_eq!(rs(source), (2, 5));
}

#[test]
fn a_cfg_test_mod_declaration_is_one_test_line() {
    assert_eq!(rs("pub fn f() {}\n\n#[cfg(test)]\nmod tests;\n"), (1, 2));
}

#[test]
fn ron_has_block_comments_and_strings() {
    let source = "// The keymap.\n(\n    /* one\n    two */\n    a: \"// x\",\n)\n";
    assert_eq!(count("files/keymap.ron", source), (3, 0));
}

#[test]
fn other_extensions_use_their_own_marker_or_none() {
    let hashed = "# a comment\nkey = 1\n\n  # indented\n";
    assert_eq!(count("Cargo.toml", hashed), (1, 0));
    assert_eq!(count(".github/workflows/ci.yml", hashed), (1, 0));
    assert_eq!(count("files/x.dlg", "# who\nlord: Hello.\n"), (1, 0));
    assert_eq!(count("files/x.map", "// rows\n#..#\n"), (1, 0));
    // No marker: the `#` line counts.
    assert_eq!(count("files/x.txt", "# heading\nplain\n\n"), (2, 0));
}

fn files(list: &[(&str, &[u8])]) -> BTreeMap<String, Vec<u8>> {
    list.iter()
        .map(|(path, bytes)| ((*path).to_owned(), bytes.to_vec()))
        .collect()
}

#[test]
fn every_file_of_a_fixture_folder_gets_its_kind() {
    let fixture = files(&[
        ("files/LICENSE-font.txt", b"Permission is granted\n"),
        (
            "files/font/atlas.ron",
            b"// Generated by `shuyi font-atlas` from a.bdf. Do not edit.\n(a: 1)\n",
        ),
        ("files/logo.png", &[0x89, b'P', b'N', b'G', 0xff, 0xfe]),
        ("README.md", b"# A game\n"),
        ("target/debug/build.rs", b"fn main() {}\n"),
        (
            ".claude/skills/shuyi-test/example/walk.rs",
            b"fn walk() {}\n",
        ),
        ("files/x.dlg", b"# the lord\nlord: Hello.\n\nlord: Bye.\n"),
        ("files/x.txt", b"# no marker\ntext\n"),
        (".gitignore", b"/target\n"),
        ("Cargo.lock", b"version = 4\n"),
        ("src/main.rs", b"fn main() {}\n"),
        ("build.rs", b"fn main() {}\n"),
        ("examples/tools.rs", b"fn main() {}\n"),
        ("tests/play.rs", b"#[test]\nfn plays() {}\n"),
        ("src/ui/tests.rs", b"fn t() {}\n"),
        ("Cargo.toml", b"[package]\nname = \"g\"\n"),
        (".cargo/config.toml", b"[alias]\n"),
        (".github/workflows/ci.yml", b"on: push\n"),
        ("files-src/font.bdf", b"STARTFONT 2.1\n"),
    ]);
    let counts = count_files("game", &fixture);
    let kinds: BTreeMap<&str, Kind> = counts
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.kind))
        .collect();
    let expected = [
        ("files/LICENSE-font.txt", Kind::LeftOut),
        ("files/font/atlas.ron", Kind::LeftOut),
        ("files/logo.png", Kind::LeftOut),
        ("README.md", Kind::LeftOut),
        ("target/debug/build.rs", Kind::LeftOut),
        (".claude/skills/shuyi-test/example/walk.rs", Kind::LeftOut),
        ("files/x.dlg", Kind::Data),
        ("files/x.txt", Kind::Data),
        (".gitignore", Kind::LeftOut),
        ("Cargo.lock", Kind::LeftOut),
        ("src/main.rs", Kind::Code),
        ("build.rs", Kind::Code),
        ("examples/tools.rs", Kind::Code),
        ("tests/play.rs", Kind::Tests),
        ("src/ui/tests.rs", Kind::Tests),
        ("Cargo.toml", Kind::Setup),
        (".cargo/config.toml", Kind::Setup),
        (".github/workflows/ci.yml", Kind::Setup),
        ("files-src/font.bdf", Kind::LeftOut),
    ];
    for (path, kind) in expected {
        assert_eq!(kinds.get(path), Some(&kind), "{path}");
    }
    assert_eq!(
        (counts.code, counts.tests, counts.data, counts.setup),
        (3, 3, 4, 4)
    );
    assert!(
        counts
            .files
            .iter()
            .filter(|f| f.kind == Kind::LeftOut)
            .all(|f| f.lines == 0)
    );
}

#[test]
fn a_code_files_test_items_count_as_tests() {
    let fixture = files(&[(
        "src/lib.rs",
        b"pub fn f() {}\n#[cfg(test)]\nmod tests {\n    fn t() {}\n}\n",
    )]);
    let counts = count_files("game", &fixture);
    assert_eq!((counts.code, counts.tests), (1, 4));
    assert_eq!(counts.files[0].test_lines, 4);
}

fn counted(code: &[(&str, usize)]) -> Counts {
    Counts {
        folder: "blank".to_owned(),
        code: code.iter().map(|(_, n)| n).sum(),
        files: code
            .iter()
            .map(|(path, lines)| File {
                path: (*path).to_owned(),
                kind: Kind::Code,
                lines: *lines,
                test_lines: 0,
            })
            .collect(),
        ..Counts::default()
    }
}

fn cap(code: usize) -> Budget {
    Budget {
        template: "blank".to_owned(),
        code,
    }
}

#[test]
fn the_cap_passes_under_and_equal() {
    let counts = counted(&[("src/lib.rs", 200), ("build.rs", 5)]);
    assert_eq!(check(&counts, &cap(205)), Vec::<String>::new());
    assert_eq!(check(&counts, &cap(210)), Vec::<String>::new());
    assert_eq!(check(&counts, &cap(214)), Vec::<String>::new());
}

#[test]
fn over_the_cap_names_the_five_biggest_code_files_and_the_engine() {
    let counts = counted(&[
        ("a.rs", 10),
        ("b.rs", 60),
        ("c.rs", 30),
        ("d.rs", 50),
        ("e.rs", 20),
        ("f.rs", 40),
    ]);
    let errors = check(&counts, &cap(209));
    assert_eq!(errors.len(), 1);
    let error = &errors[0];
    assert!(
        error.contains(
            "b.rs (60), d.rs (50), f.rs (40), c.rs (30), e.rs (20). Don't raise the cap: a part \
             every new game needs goes in the engine"
        ),
        "{error}"
    );
    assert!(!error.contains("a.rs"), "{error}");
    assert!(
        error.starts_with("blank: 210 code lines, over the cap of 209"),
        "{error}"
    );
}

#[test]
fn ten_or_more_above_the_count_asks_to_lower_the_cap() {
    let counts = counted(&[("src/lib.rs", 201)]);
    assert_eq!(
        check(&counts, &cap(211)),
        vec![
            "blank: 201 code lines, 10 under the cap of 211: lower `code` to 210 in \
             tools/line-budget.ron"
                .to_owned()
        ]
    );
    assert_eq!(check(&counts, &cap(210)), Vec::<String>::new());
}

