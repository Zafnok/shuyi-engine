param([switch]$Check)

# .claude/skills stays the shared source so existing links and the game's
# pinned engine skill-pack updater keep working. Codex discovers these loaders.
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$sourceRoot = Join-Path $repoRoot '.claude/skills'
$loaderRoot = Join-Path $repoRoot '.agents/skills'
$marker = '<!-- Generated by scripts/sync-agent-skills.ps1; edit the shared source. -->'
$utf8 = [System.Text.UTF8Encoding]::new($false)
$problems = [System.Collections.Generic.List[string]]::new()
$expected = @{}

foreach ($source in Get-ChildItem -LiteralPath $sourceRoot -Directory | Sort-Object Name) {
    $manifest = Join-Path $source.FullName 'SKILL.md'
    if (-not (Test-Path -LiteralPath $manifest)) { continue }
    $text = [System.IO.File]::ReadAllText($manifest).Replace("`r`n", "`n")
    $frontmatter = [regex]::Match($text, '\A---\n.*?\n---\n', 'Singleline')
    if (-not $frontmatter.Success) { throw "Missing frontmatter: $manifest" }
    $name = $source.Name
    $body = @"
$marker

Read and follow the [shared $name skill](../../../.claude/skills/$name/SKILL.md).
Resolve its relative links and supporting resources from that source folder.
The shared workflow applies with any model or provider; use the tools available
in the current harness while preserving its checks and authorization boundaries.
"@
    # Codex's manifest validator rejects angle brackets in descriptions.
    # Keep the pinned/shared source intact and normalize the discovery text.
    $header = [regex]::Replace($frontmatter.Value, '(?m)^description: (?![>|]).+$', {
        param($match)
        $match.Value.Replace('<', '').Replace('>', '')
    })
    $wanted = $header + "`n" + $body.Replace("`r`n", "`n") + "`n"
    $expected[$name] = $true
    $destination = Join-Path $loaderRoot "$name/SKILL.md"
    if (Test-Path -LiteralPath $destination) {
        $current = [System.IO.File]::ReadAllText($destination).Replace("`r`n", "`n")
        if ($current -eq $wanted) { continue }
        if (-not $current.Contains($marker)) {
            throw "Refusing to replace an unmanaged skill: $destination"
        }
    }
    if ($Check) {
        $problems.Add(".agents/skills/$name/SKILL.md is missing or out of date")
    } else {
        [System.IO.Directory]::CreateDirectory((Split-Path $destination -Parent)) | Out-Null
        [System.IO.File]::WriteAllText($destination, $wanted, $utf8)
    }
}

if (Test-Path -LiteralPath $loaderRoot) {
    foreach ($folder in Get-ChildItem -LiteralPath $loaderRoot -Directory) {
        if ($expected.ContainsKey($folder.Name)) { continue }
        $manifest = Join-Path $folder.FullName 'SKILL.md'
        if ((Test-Path -LiteralPath $manifest) -and
            [System.IO.File]::ReadAllText($manifest).Contains($marker)) {
            # Report stale loaders; never delete a skill or supporting files.
            $problems.Add(".agents/skills/$($folder.Name)/SKILL.md has no shared source; remove the stale loader")
        }
    }
}

if ($problems.Count) { throw ($problems -join "`n") }
Write-Output "agent skills: $($expected.Count) shared skills available to both harnesses"
